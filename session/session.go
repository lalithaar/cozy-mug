// Package session provides cookie-backed sessions and CSRF protection for
// cozy-mug apps (ADR 0013).
//
// A session is a small map stored entirely in a client cookie, sealed with
// AES-256-GCM. The framework keeps no server-side session state: the cookie is
// opaque and tamper-evident, survives restarts, and needs no store. Keep
// sessions small — a session too large for a cookie is not persisted.
package session

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"os"
	"time"

	"github.com/lalithaar/cozy-mug/core"
)

// DefaultName is the cookie name used when Options.Name is empty.
const DefaultName = "cozy_session"

// csrfSlot is the session key holding the CSRF token.
const csrfSlot = "csrf"

// maxCookieValue keeps the sealed cookie under the 4 KB browser limit.
const maxCookieValue = 3600

// Options configures a Store.
type Options struct {
	// Key seals the cookie. It must be exactly 32 bytes (AES-256) and must come
	// from the environment (see Key). Required.
	Key []byte

	// Name is the cookie name; DefaultName when empty.
	Name string

	// Secure sets the cookie's Secure attribute. Turn it on in production (HTTPS).
	Secure bool

	// SameSite defaults to Lax when zero.
	SameSite http.SameSite

	// MaxAge is the cookie lifetime; 0 is a browser-session cookie.
	MaxAge time.Duration

	// DisableCSRF turns off CSRF enforcement in Middleware (sessions still work).
	DisableCSRF bool
}

// Store seals and opens session cookies. It is safe for concurrent use.
type Store struct {
	aead        cipher.AEAD
	name        string
	secure      bool
	sameSite    http.SameSite
	maxAge      time.Duration
	enforceCSRF bool
}

// New builds a Store. It is boot-only: a bad key is a programming error.
func New(opts Options) (*Store, error) {
	if len(opts.Key) != 32 {
		return nil, fmt.Errorf("session: Options.Key must be 32 bytes, got %d", len(opts.Key))
	}
	block, err := aes.NewCipher(opts.Key)
	if err != nil {
		return nil, fmt.Errorf("session: cipher: %w", err)
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("session: gcm: %w", err)
	}
	name := opts.Name
	if name == "" {
		name = DefaultName
	}
	sameSite := opts.SameSite
	if sameSite == 0 {
		sameSite = http.SameSiteLaxMode
	}
	return &Store{
		aead:        aead,
		name:        name,
		secure:      opts.Secure,
		sameSite:    sameSite,
		maxAge:      opts.MaxAge,
		enforceCSRF: !opts.DisableCSRF,
	}, nil
}

// Key decodes a base64, 32-byte key from the named environment variable. A
// missing or malformed key is an error; the value is never echoed (secrets
// heuristic). Generate one with: openssl rand -base64 32.
func Key(env string) ([]byte, error) {
	v := os.Getenv(env)
	if v == "" {
		return nil, fmt.Errorf("session: %s is not set", env)
	}
	b, err := base64.StdEncoding.DecodeString(v)
	if err != nil {
		return nil, fmt.Errorf("session: %s is not valid base64", env)
	}
	if len(b) != 32 {
		return nil, fmt.Errorf("session: %s must decode to 32 bytes, got %d", env, len(b))
	}
	return b, nil
}

// Middleware loads the session, enforces CSRF on unsafe methods, runs the
// handler, then persists any change. Install it inside the Errors middleware and
// before the views so templates can read the session.
func (s *Store) Middleware(next core.Handler) core.Handler {
	return func(c *core.Context) core.Response {
		sess := s.load(c.R)
		c.R = core.WithSession(c.R, sess)

		if s.enforceCSRF && !safeMethod(c.Method()) {
			if err := s.checkCSRF(c, sess); err != nil {
				return c.Error(err)
			}
		}

		resp := next(c)
		s.persist(c, sess)
		return resp
	}
}

// Session is this request's session: a small map with an id and a CSRF token. It
// satisfies core.Session and adds typed getters. It is not safe for concurrent
// use; a request is single-goroutine.
type Session struct {
	id        string
	data      map[string]any
	dirty     bool
	destroyed bool
}

func (s *Store) load(r *http.Request) *Session {
	if ck, err := r.Cookie(s.name); err == nil {
		if sess, err := s.open(ck.Value); err == nil {
			return sess
		}
	}
	return &Session{id: newID(), data: map[string]any{}}
}

// From returns the request's session as the concrete *Session, or nil when the
// app did not configure sessions. It is the typed accessor for the richer
// helpers (GetString, GetInt64, ID) that the core seam does not expose.
func From(c *core.Context) *Session {
	s, _ := c.Session().(*Session)
	return s
}

// ID is the session's identifier (regenerated by Regenerate).
func (s *Session) ID() string { return s.id }

// Get returns the value stored at key, or nil.
func (s *Session) Get(key string) any { return s.data[key] }

// GetString returns the value at key as a string ("" if absent or not a string).
func (s *Session) GetString(key string) string {
	v, _ := s.data[key].(string)
	return v
}

// GetInt64 returns the value at key as an int64, accepting JSON's float64, or 0.
func (s *Session) GetInt64(key string) int64 {
	switch v := s.data[key].(type) {
	case int64:
		return v
	case int:
		return int64(v)
	case float64:
		return int64(v)
	}
	return 0
}

// Set stores a value. Values are JSON-encoded when the cookie is written, so
// keep them small and JSON-friendly.
func (s *Session) Set(key string, value any) {
	s.data[key] = value
	s.dirty = true
}

// Delete removes a key.
func (s *Session) Delete(key string) {
	if _, ok := s.data[key]; ok {
		delete(s.data, key)
		s.dirty = true
	}
}

// Clear removes every key but keeps the session (and its id).
func (s *Session) Clear() {
	s.data = map[string]any{}
	s.dirty = true
}

// Dirty reports whether the session changed and needs to be written back.
func (s *Session) Dirty() bool { return s.dirty }

// Regenerate gives the session a fresh id and empty contents — call it on login
// to prevent session fixation. The CSRF token is regenerated with it.
func (s *Session) Regenerate() {
	s.id = newID()
	s.data = map[string]any{}
	s.dirty = true
}

// Destroy empties the session and clears its cookie.
func (s *Session) Destroy() {
	s.data = map[string]any{}
	s.destroyed = true
	s.dirty = true
}

// CSRFToken returns the CSRF token, creating one on first use. It is stored in
// the sealed cookie, so a cross-site attacker cannot read it.
func (s *Session) CSRFToken() string {
	if t, ok := s.data[csrfSlot].(string); ok && t != "" {
		return t
	}
	t := randToken()
	s.data[csrfSlot] = t
	s.dirty = true
	return t
}

// checkCSRF compares the submitted token (header X-CSRF-Token, else form field
// "csrf") against the session's token in constant time.
func (s *Store) checkCSRF(c *core.Context, sess *Session) error {
	want, _ := sess.data[csrfSlot].(string)
	got := c.R.Header.Get("X-CSRF-Token")
	if got == "" {
		got = c.R.PostFormValue("csrf")
	}
	if want == "" || got == "" || subtle.ConstantTimeCompare([]byte(want), []byte(got)) != 1 {
		return core.Forbidden(errors.New("session: CSRF token missing or invalid"))
	}
	return nil
}

// persist writes (or clears) the session cookie.
func (s *Store) persist(c *core.Context, sess *Session) {
	if sess.destroyed {
		http.SetCookie(c.W, &http.Cookie{
			Name: s.name, Value: "", Path: "/", HttpOnly: true,
			Secure: s.secure, SameSite: s.sameSite, MaxAge: -1,
		})
		return
	}
	if !sess.dirty {
		return
	}
	value, err := s.seal(sess)
	if err != nil || len(value)+len(s.name) > maxCookieValue {
		return // unsealable or too large for a cookie
	}
	maxAge := 0
	if s.maxAge > 0 {
		maxAge = int(s.maxAge.Seconds())
	}
	http.SetCookie(c.W, &http.Cookie{
		Name: s.name, Value: value, Path: "/", HttpOnly: true,
		Secure: s.secure, SameSite: s.sameSite, MaxAge: maxAge,
	})
}

type payload struct {
	ID   string         `json:"id"`
	Data map[string]any `json:"d"`
}

func (s *Store) seal(sess *Session) (string, error) {
	raw, err := json.Marshal(payload{ID: sess.id, Data: sess.data})
	if err != nil {
		return "", err
	}
	nonce := make([]byte, s.aead.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		return "", err
	}
	out := s.aead.Seal(nil, nonce, raw, nil)
	return base64.RawURLEncoding.EncodeToString(append(nonce, out...)), nil
}

func (s *Store) open(value string) (*Session, error) {
	raw, err := base64.RawURLEncoding.DecodeString(value)
	if err != nil {
		return nil, err
	}
	ns := s.aead.NonceSize()
	if len(raw) < ns {
		return nil, errors.New("session: cookie too short")
	}
	plain, err := s.aead.Open(nil, raw[:ns], raw[ns:], nil)
	if err != nil {
		return nil, err
	}
	var p payload
	if err := json.Unmarshal(plain, &p); err != nil {
		return nil, err
	}
	if p.Data == nil {
		p.Data = map[string]any{}
	}
	return &Session{id: p.ID, data: p.Data}, nil
}

// safeMethod reports whether an HTTP method is safe from CSRF (no side effects).
func safeMethod(m string) bool {
	switch m {
	case http.MethodGet, http.MethodHead, http.MethodOptions, http.MethodTrace:
		return true
	}
	return false
}

func randToken() string {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		panic("session: crypto/rand: " + err.Error())
	}
	return base64.RawURLEncoding.EncodeToString(b)
}

func newID() string { return randToken() }
